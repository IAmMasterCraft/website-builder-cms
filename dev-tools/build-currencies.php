<?php
declare(strict_types=1);

/*
 * Builds src/geo/currencies.php (country code => ISO 4217 currency code)
 * from GeoNames countryInfo.txt (CC BY 4.0, see CREDITS.md), the same dump
 * dev-tools/build-geo.php reads. Used for the installer's currency guess (D2).
 *   php dev-tools/build-currencies.php [dev-tools/geo-src/countryInfo.txt]
 */
$src = $argv[1] ?? __DIR__ . '/geo-src/countryInfo.txt';
$fh = fopen($src, 'rb');
if ($fh === false) {
    fwrite(STDERR, "Cannot read $src\n");
    exit(1);
}
$map = [];
while (($line = fgets($fh)) !== false) {
    if ($line === '' || $line[0] === '#') {
        continue;
    }
    $f = explode("\t", rtrim($line, "\r\n"));
    if (isset($f[0], $f[10]) && preg_match('/^[A-Z]{2}$/', $f[0]) && preg_match('/^[A-Z]{3}$/', $f[10])) {
        $map[$f[0]] = $f[10];
    }
}
ksort($map);
$out = "<?php\n// Generated by dev-tools/build-currencies.php from GeoNames countryInfo.txt (CC BY 4.0). Do not edit.\nreturn " . var_export($map, true) . ";\n";
file_put_contents(dirname(__DIR__) . '/src/geo/currencies.php', $out);
echo count($map) . " countries\n";
